"""Guards for the documentation: referenced commands/files exist and author credits stay."""
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ["README.md", "CONTRIBUTING.md", "ATTRIBUTION.md", "LICENSING.md", "docs/PUBLISHING.md"]
SUBCOMMANDS = {"setup", "check", "serve", "test", "lint", "train", "smoke", "audit"}


def text(name):
    return (ROOT / name).read_text(encoding="utf-8")


class DocsTests(unittest.TestCase):
    def test_dev_subcommands_mentioned_in_docs_exist(self):
        for doc in DOCS:
            for cmd in re.findall(r"scripts[/\\]dev\.py\s+([a-z]+)", text(doc)):
                self.assertIn(cmd, SUBCOMMANDS, f"{doc} mentions unknown command 'dev.py {cmd}'")

    def test_subcommands_in_this_test_match_dev_py(self):
        src = text("scripts/dev.py")
        for cmd in SUBCOMMANDS:
            self.assertIn(f'sub.add_parser("{cmd}"', src)

    def test_files_referenced_in_docs_exist(self):
        roots = "scripts|service|training|worker|tests|docs|requirements|prompts|data|tools"
        pat = re.compile(rf"`((?:{roots})/[A-Za-z0-9_./-]+)`")
        for doc in DOCS:
            for ref in pat.findall(text(doc)):
                ref = ref.rstrip(".,")
                if any(ch in ref for ch in "*<>") or ref.endswith("/"):
                    continue
                if ref.startswith(("data/train", "data/smoke", "data/clean_stats")):
                    continue  # generated by the user
                self.assertTrue((ROOT / ref).exists(), f"{doc} references missing path {ref}")

    def test_every_env_variable_in_example_is_documented_in_readme(self):
        names = re.findall(r"^#?\s*([A-Z][A-Z0-9_]+)=", text(".env.example"), flags=re.M)
        readme = text("README.md")
        for n in set(names):
            if n.startswith("AWS_"):
                n = "AWS_"
            self.assertIn(n, readme, f"{n} is in .env.example but not explained in the README")

    def test_original_author_credits_are_preserved(self):
        for name in ("README.md", "ATTRIBUTION.md", "STATUS.md", "AI_USE.md"):
            body = text(name)
            self.assertIn("Vivek Sagarwal", body, name)
            self.assertIn("Pratham Gupta", body, name)

    def test_no_license_is_claimed_without_the_rights_holder(self):
        self.assertFalse((ROOT / "LICENSE").exists(),
                         "a LICENSE file may only be added after the rights holder agrees (see LICENSING.md)")
        self.assertIn("NOT IN FORCE", text("docs/LICENSE.mit.template"))

    def test_env_example_contains_no_real_looking_secrets(self):
        for line in text(".env.example").splitlines():
            if line.startswith(("AWS_ACCESS_KEY_ID=", "AWS_SECRET_ACCESS_KEY=")):
                self.assertEqual(line.split("=", 1)[1], "", line)


if __name__ == "__main__":
    unittest.main()
